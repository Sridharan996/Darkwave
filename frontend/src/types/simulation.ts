/**
 * DARKWAVE - Autonomous Marine Supplemental Lighting System
 * Simulation & State Definitions
 */

export type WeatherMode = 'SUNLIGHT' | 'CLOUDY' | 'RAINY';

export type SimulationStateMode =
  | 'SUNLIGHT'
  | 'CLOUDY'
  | 'RAINY'
  | 'NORMAL_DAY'
  | 'CLOUDY_EVENT'
  | 'STORM_CONDITION'
  | 'PERSISTENT_LOW_LIGHT'
  | 'SUNLIGHT_RESTORED'
  | 'MANUAL_CUSTOM';

export type ProgressionStage =
  | 'SUNLIGHT_STABLE'
  | 'WEATHER_TRANSITION'
  | 'LIGHT_DECREASING'
  | 'LOW_LIGHT_DETECTED'
  | 'TIMER_COUNTING'
  | 'ML_EVALUATING'
  | 'LED_ACTIVATED'
  | 'SUNLIGHT_RECOVERY'
  | 'LED_DEACTIVATED';

export type DemoPhase =
  | 'IDLE'
  | 'SUNNY'
  | 'CLOUDS_ARRIVE'
  | 'LOW_LIGHT_DETECTED'
  | 'PERSISTENCE_TIMER'
  | 'ML_PREDICTION'
  | 'LED_ON'
  | 'SUNLIGHT_RETURNS'
  | 'LED_OFF_RESET';

export type SystemMode = 'AUTONOMOUS' | 'MANUAL_OVERRIDE' | 'DIAGNOSTIC' | 'STANDBY';

export type LightingState = 'INACTIVE' | 'PENDING_VERIFICATION' | 'ACTIVE_SUPPLEMENTAL' | 'SAFETY_LOCKOUT';

export interface EnvironmentalConditions {
  cloudCoverPercent: number; // 0 to 100%
  solarIrradiance: number; // W/m^2 (0 to 1200)
  underwaterLightLevel: number; // Lux (0 to 5000)
  turbidity: number; // NTU (0 to 100)
  waterTemperature: number; // Celsius (e.g. 26.8 °C)
  phLevel: number; // pH (e.g. 8.1)
  timeOfDay: number; // 0.0 to 24.0 hours
  waveHeight: number; // meters
}

export type PowerSystemStateMode = 'NORMAL' | 'BACKUP' | 'CRITICAL';

export interface PowerSystemConfig {
  batteryNominalVoltage: number; // V (e.g. 12.8V LiFePO4)
  batteryCapacityAh: number; // Ah (e.g. 50.0 Ah)
  maxUsableDoD: number; // 0.0 - 1.0 (e.g. 0.85 = 85% Depth of Discharge)
  powerConversionEfficiency: number; // 0.0 - 1.0 (e.g. 0.92 = 92% MPPT / DC-DC efficiency)
  esp32PowerWatts: number; // W (e.g. 1.2W)
  sensorPowerWatts: number; // W (e.g. 0.8W)
  loraPowerWatts: number; // W (e.g. 0.5W)
  ledNominalPowerWatts: number; // W (e.g. 60.0W @ 100%)
  stormAutonomyTargetHours: number; // e.g. 96.0 hours (4 days of zero/low solar)
  criticalSocThresholdPercent: number; // % (e.g. 15.0%)
}

export interface PowerSystemTelemetry {
  config: PowerSystemConfig;
  powerState: PowerSystemStateMode;
  solarGenerationWatts: number; // W generated by PV panel
  baseLoadWatts: number; // W (ESP32 + Sensors + LoRa)
  ledLoadWatts: number; // W (LED load only while LED is active)
  totalLoadWatts: number; // W (baseLoadWatts + ledLoadWatts)
  netPowerWatts: number; // W (solarGenerationWatts - totalLoadWatts)
  batteryTotalCapacityWh: number; // Wh = NominalVoltage * CapacityAh
  batteryUsableCapacityWh: number; // Wh = TotalWh * DoD * Efficiency
  batteryEnergyRemainingWh: number; // Wh live remaining
  batteryUsableEnergyRemainingWh: number; // Wh remaining above DoD cutoff
  batterySocPercent: number; // % (0 to 100%)
  batteryVoltage: number; // V dynamic curve
  batteryCurrentAmps: number; // A (positive = charging, negative = discharging)
  estimatedRuntimeHours: number; // Usable Energy (Wh) / Total Load (W)
  stormDurationHours: number; // Hours elapsed in low-solar / storm condition
  stormBackupModeActive: boolean; // True when solar is low / cloudy / storm
  autonomyTargetHours: number; // 96.0 h
  has96HourAutonomy: boolean; // true if usable capacity >= 96h requirement
  requiredAdditionalWh: number; // >0 if insufficient
  autonomyStatusMessage: string; // "96-HOUR STORM AUTONOMY AVAILABLE" or "BACKUP CAPACITY INSUFFICIENT"
  energyConservationActive: boolean; // True when critical
}

export interface BuoyHardwareTelemetry {
  batteryVoltage: number; // V
  batteryChargePercent: number; // %
  solarPanelOutputWatts: number; // W
  esp32CoreTemp: number; // °C
  loraRssi: number; // dBm
  loraSnr?: number; // dB
  ledPowerOutputWatts: number; // W
  ledIntensityPercent: number; // 0 to 100%
  ledOperatingCurrentAmps: number; // A
  ledTemperature: number; // °C
  powerSystem?: PowerSystemTelemetry;
}

export interface DecisionEngineState {
  underwaterThresholdLux: number; // e.g. 200 Lux
  persistenceDurationSeconds: number; // 5 seconds for software demonstration
  currentLowLightDurationSeconds: number; // Live accumulated 0 to 5 seconds counter
  persistenceDurationMinutes: number; // For backward compatibility
  currentLowLightDurationMinutes: number; // For backward compatibility
  isLowLightDetected: boolean;
  persistenceTimerActive: boolean;
  persistenceProgressPercent: number; // 0 to 100%
  mlIlluminationRequired: 0 | 1;
  mlConfidenceScore: number; // e.g. 0.942 (94.2%)
  decisionReason: string;
  lightingState: LightingState;
  systemMode: SystemMode;
  currentSimulationState: SimulationStateMode;
  backendConnected?: boolean;
  apiLatencyMs?: number;
}

